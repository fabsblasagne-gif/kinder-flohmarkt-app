# Kinder-Flohmarkt App

Eine moderne Flutter-App für einen Kinder-Flohmarkt mit warmem Design, Kartenlayout und Angebotsübersicht.

## Schnellstart

1. Flutter installieren
2. In das Projektverzeichnis wechseln
3. Abhängigkeiten laden:
   ```bash
   flutter pub get
   ```
4. App starten:
   ```bash
   flutter run
   ```

## Features

- Stylische Startseite mit Header
- Veranstaltungskarten mit Details
- Moderne Angebotsliste
- Button zum Hinzufügen neuer Angebote
- Material 3 Design in warmen Farben
